// Run after changing an operator tool's public schema or description.
// The broker owns handlers; stdio only needs these lazy metadata descriptors.
import ts from "typescript";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import prettier from "prettier";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../src/tools");
for (const base of ["provision-drive", "inject-card"]) {
  const source = readFileSync(resolve(root, `${base}.ts`), "utf8");
  const ast = ts.createSourceFile(`${base}.ts`, source, ts.ScriptTarget.Latest, true);
  const declarations = new Map();
  const tools = [];
  for (const statement of ast.statements) {
    if (!ts.isVariableStatement(statement)) continue;
    for (const declaration of statement.declarationList.declarations) {
      if (!ts.isIdentifier(declaration.name) || !declaration.initializer) continue;
      const name = declaration.name.text;
      if (name.endsWith("Tool") && ts.isObjectLiteralExpression(declaration.initializer))
        tools.push([name, declaration.initializer]);
      else declarations.set(name, statement);
    }
  }
  const referenced = new Set();
  if (base === "provision-drive") {
    for (const name of [
      "captureClickSchema",
      "captureExtractSchema",
      "CAPTURE_NOTE",
      "CLICK_CAPTURE_NOTE",
      "EXTRACT_CAPTURE_NOTE",
    ])
      referenced.add(name);
  }
  const visit = (node) => {
    if (ts.isIdentifier(node)) referenced.add(node.text);
    ts.forEachChild(node, visit);
  };
  const selected = new Set();
  for (const [, object] of tools)
    for (const property of object.properties) {
      if (property.name?.getText(ast) !== "handler") visit(property);
    }
  let changed = true;
  while (changed) {
    changed = false;
    for (const name of [...referenced]) {
      const statement = declarations.get(name);
      if (!statement || selected.has(statement)) continue;
      selected.add(statement);
      visit(statement);
      changed = true;
    }
  }
  const pieces = [
    "// Generated by scripts/generate-operator-schemas.mjs. Edit the source tool file.\n",
    'import { z } from "zod";',
    'import type { Tool } from "./index.js";',
    ...(base === "provision-drive"
      ? ['import { captureSourceSchema } from "../bot/credential-capture.js";']
      : []),
  ];
  for (const statement of ast.statements)
    if (selected.has(statement)) pieces.push(statement.getText(ast));
  for (const [name, object] of tools) {
    const metadata = object.properties
      .filter((p) => p.name?.getText(ast) !== "handler")
      .map((p) => p.getText(ast));
    pieces.push(
      `export const ${name}: Tool = {\n${metadata.join(",\n")},\nasync handler(args, api, context) {\n return await (await import("./${base}.js")).${name}.handler(args as never, api, context);\n}\n};`,
    );
  }
  if (base === "provision-drive") {
    pieces.push(
      source.slice(
        source.indexOf("export const OPERATE_TOOLS:"),
        source.indexOf("\n\nconst captureOutputSchema ="),
      ),
    );
    // The source applies shared capture descriptions and output metadata after declaring its tools.
    pieces.push(
      source.slice(
        source.indexOf("const captureOutputSchema = "),
        source.indexOf("  const handler = tool.handler;"),
      ) + "}\n",
    );
    pieces.push(source.slice(source.indexOf("// Keep the additive click receipt"), source.length));
  }
  const outputPath = resolve(root, `${base}-schema.ts`);
  const prettierConfig =
    base === "provision-drive" ? ((await prettier.resolveConfig(outputPath)) ?? {}) : {};
  writeFileSync(
    outputPath,
    await prettier.format(pieces.join("\n\n") + "\n", {
      ...prettierConfig,
      parser: "typescript",
    }),
  );
}
