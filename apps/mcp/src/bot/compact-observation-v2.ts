export const COMPACT_V2_HANDLE_LENGTH = 22;
const COMPACT_V2_HANDLE_RE = new RegExp(`^@e:[A-Za-z0-9_-]{${COMPACT_V2_HANDLE_LENGTH}}$`);

export class StableObservationRefs {
  private document: string | undefined;
  private generation = 0;
  private refs = new Map<string, string>();
  private identities = new Map<string, string>();
  private anchors = new Map<string, { intent: string; ref: string }>();
  private aliases = new Map<string, string>();
  private aliasOwners = new Map<string, string>();
  private reset(document: string): void {
    if (this.document === document) return;
    this.document = document;
    this.generation++;
    this.refs.clear();
    this.identities.clear();
    this.anchors.clear();
    this.aliases.clear();
    this.aliasOwners.clear();
  }

  /** Reconcile the full live inventory, retiring absent or materially changed nodes. */
  actions(
    document: string,
    elements: readonly InteractiveElement[],
  ): Map<InteractiveElement, string> {
    this.reset(document);
    const present = new Set(elements.map((el) => el.observationIdentity));
    for (const identity of this.anchors.keys()) {
      if (!present.has(identity)) this.anchors.delete(identity);
    }
    const counts = new Map<string, number>();
    for (const el of elements) {
      if (el.observationIdentity)
        counts.set(el.observationIdentity, (counts.get(el.observationIdentity) ?? 0) + 1);
    }
    const handles = new Map<InteractiveElement, string>();
    for (const el of elements) {
      const identity = el.observationIdentity;
      if (!identity || el.observationIntent === undefined || counts.get(identity) !== 1) {
        if (identity) this.anchors.delete(identity);
        continue;
      }
      let anchor = this.anchors.get(identity);
      if (!anchor || anchor.intent !== el.observationIntent) {
        anchor = {
          intent: el.observationIntent,
          ref: this.get(document, `action:${randomBytes(32).toString("base64url")}`),
        };
        this.anchors.set(identity, anchor);
      }
      handles.set(el, anchor.ref);
    }
    return handles;
  }

  /** Distinguish an unknown label from a retired alias in this document. */
  hasLabel(label: string): boolean {
    return this.aliasOwners.has(label);
  }

  /** Compatibility spelling of one capability; never reassign an old alias. */
  label(ref: string, preferred: string | undefined): string | undefined {
    const existing = this.aliases.get(ref);
    if (existing !== undefined || preferred === undefined) return existing;
    let candidate = preferred;
    for (let suffix = 2; this.aliasOwners.has(candidate); suffix++)
      candidate = labelWithOrdinalV2(preferred, suffix);
    this.aliases.set(ref, candidate);
    this.aliasOwners.set(candidate, ref);
    return candidate;
  }

  constructor(private readonly secret: Buffer<ArrayBufferLike> = randomBytes(32)) {}
  get(document: string, identity: string): string {
    this.reset(document);
    let ref = this.refs.get(identity);
    if (ref === undefined) {
      for (let collision = 0; ; collision++) {
        const candidate = `@e:${createHmac("sha256", this.secret)
          .update(document)
          .update("\u0000")
          .update(String(this.generation))
          .update("\u0000")
          .update(identity)
          .update("\u0000")
          .update(String(collision))
          .digest("base64url")
          .slice(0, COMPACT_V2_HANDLE_LENGTH)}`;
        const owner = this.identities.get(candidate);
        if (owner === undefined || owner === identity) {
          ref = candidate;
          this.identities.set(ref, identity);
          break;
        }
      }
      this.refs.set(identity, ref);
    }
    return ref;
  }
}
const LABEL_MAX_CHARS = 32;
const COMPACT_V2_LABEL_RE = /^@[\p{L}\p{M}\p{N}]+(?:-[\p{L}\p{M}\p{N}]+)*(?:…)?$/u;

export function isCompactV2Handle(target: string): boolean {
  return COMPACT_V2_HANDLE_RE.test(target);
}

/** The `@label` alias form, distinguishable from a handle by its `@e:` prefix. */
export function isCompactV2Label(target: string): boolean {
  return (
    COMPACT_V2_LABEL_RE.test(target) &&
    /[\p{L}\p{N}]/u.test(target) &&
    Array.from(target.slice(1)).length <= LABEL_MAX_CHARS
  );
}

/**
 * Resolve a handle only when it is well-formed AND a member of the current
 * snapshot's action map. Callers must never turn an unknown @e: value into a
 * label or legacy-ref lookup. The handle is document-scoped by construction
 * (the allocator retires its document map), so a ref from a replaced document finds no
 * live match rather than resolving onto whatever now occupies its position.
 */
export function compactV2LegacyRefForHandle(
  handles: ReadonlyMap<string, string>,
  target: string,
): string | null {
  if (!isCompactV2Handle(target)) return null;
  return handles.get(target) ?? null;
}

/**
 * Split a glued "Title + description" accessible name into its leading title,
 * detected from the ORIGINAL name — by slug time the boundary is gone. The
 * 2026-09-06 ipinfo docs dogfood produced labels like
 * `@database-downloadsdownload-ip-da`: two headings (or a heading and its
 * description) concatenated by the DOM with no whitespace, slugified into one
 * unreadable run and hard-cut mid-word. The boundaries that mark that seam in
 * the original name are:
 * - a newline inside the accessible name,
 * - sentence/heading punctuation (`.` `!` `?` `:` `)`) directly abutting the
 *   next word (`(Search Ctrl+K)Navigation`, `Docs.Start here`) — a period
 *   followed by a lowercase letter ("Node.js") is NOT a boundary,
 * - a lowercase→uppercase case transition where two headings were joined
 *   with no space (`DownloadsDownload`).
 * Returns the original name when no qualifying boundary is found, so ordinary
 * multi-word names and short glued pairs keep their full slug.
 */
function leadingTitleFromAccessibleName(name: string): string {
  // A candidate title must read as a heading — multi-word, or a substantial
  // standalone word — so camelCase identifiers ("myAccountSettings") and
  // abbreviation fragments ("U.S. Government") keep their full slug, and a
  // real description must remain behind the seam.
  const readsAsHeading = (title: string): boolean =>
    /[A-Za-z0-9]/.test(title) && (title.includes(" ") || title.length >= 5);
  const hasDescription = (rest: string): boolean => /[A-Za-z0-9].*[A-Za-z0-9]/.test(rest);
  for (let i = 0; i < name.length - 1; i += 1) {
    const ch = name[i]!;
    const next = name[i + 1]!;
    if (ch === "\n") {
      if (readsAsHeading(name.slice(0, i)) && hasDescription(name.slice(i + 1))) {
        return name.slice(0, i);
      }
      continue;
    }
    if (".!?:)".includes(ch) && /[A-Za-z0-9]/.test(next)) {
      // A period followed by a lowercase letter is an abbreviation
      // ("Node.js"), not a heading seam; require an uppercase letter (or a
      // closing parenthesis, which abuts a seam regardless of case).
      if ((ch === ")" || /[A-Z]/.test(next)) && hasDescription(name.slice(i + 1))) {
        const title = name.slice(0, i);
        if (readsAsHeading(title)) return title;
      }
      continue;
    }
    if (/[a-z]/.test(ch) && /[A-Z]/.test(next)) {
      const title = name.slice(0, i + 1);
      if (readsAsHeading(title) && hasDescription(name.slice(i + 1))) return title;
    }
  }
  return name;
}

/** Addressable slug of the page's control description, with the existing title and length limits. */
export function controlLabelV2(description: string | undefined): string | undefined {
  if (description === undefined) return undefined;
  const titled = leadingTitleFromAccessibleName(description);
  let slug = titled
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[^\p{L}\p{M}\p{N}]+/gu, "-")
    .replace(/^-+|-+$/gu, "");
  let characters = Array.from(slug);
  const truncated = characters.length > LABEL_MAX_CHARS;
  const usesUnicode = characters.some((character) => character.charCodeAt(0) > 0x7f);
  if (truncated) {
    characters = characters.slice(0, LABEL_MAX_CHARS - Number(usesUnicode));
    // Never cut mid-word: drop the trailing partial segment at the last word
    // boundary. A single unbroken run longer than the budget keeps its
    // mid-run cut — there is no boundary to cut on.
    const lastBoundary = characters.lastIndexOf("-");
    if (lastBoundary > 0) characters = characters.slice(0, lastBoundary);
  }
  slug = characters.join("").replace(/-+$/g, "");
  if (slug.length === 0 || !/[\p{L}\p{N}]/u.test(slug)) return undefined;
  return `@${slug}${truncated && usesUnicode ? "…" : ""}`;
}

function labelWithOrdinalV2(label: string, suffix: number): string {
  const tail = `-${suffix}`;
  const characters = Array.from(label.slice(1));
  const truncated =
    characters.length > LABEL_MAX_CHARS - Array.from(tail).length || characters.at(-1) === "…";
  const body = truncated ? characters.slice(0, -1) : characters;
  const limit = LABEL_MAX_CHARS - Array.from(tail).length - Number(truncated);
  return `@${body.slice(0, limit).join("")}${tail}${truncated ? "…" : ""}`;
}

type WireControlV2 = [string, string, string?];

// The protocol is intentionally positional to keep repeated observes small.
// Tuple schema: [ref, role(b/l/t/s/c/r/tb/m/f), optional compact description].
// The description starts with the `@label` alias (itself a valid act target)
// and appends only present code-owned facts (`s=`, `a=`, `f=`, `q=`, `x=`,
// and query-only `m=` provenance). It
// is deliberately one sparse string rather than nullable columns:
// checked/unchecked, disabled, action, field, card choice, and frame context
// remain distinguishable without paying for empty slots on every row. The
// label grammar excludes `|` and `=`, so no escaping is needed.
function wireControl(row: SafeControlV2): WireControlV2 {
  const role: Record<SafeRoleV2, string> = {
    button: "b",
    link: "l",
    textbox: "t",
    select: "s",
    checkbox: "c",
    radio: "r",
    tab: "tb",
    menuitem: "m",
    file: "f",
  };
  const facts = [
    row.label,
    ...(row.visibility === "near" ? ["v=offscreen"] : []),
    ...(row.state === undefined ? [] : [`s=${row.state}`]),
    ...(row.action === undefined ? [] : [`a=${row.action}`]),
    ...(row.field === undefined ? [] : [`f=${row.field}`]),
    ...(row.choice === undefined ? [] : [`q=${row.choice}`]),
    ...(row.frame === "main" ? [] : [`x=${row.frame === "same_origin" ? "s" : "x"}`]),
    ...(row.match === undefined
      ? []
      : [`m=${{ name: "n", role: "r", text: "t", context: "c" }[row.match]}`]),
  ].filter((value): value is string => value !== undefined);
  return facts.length === 0
    ? [row.ref, Object.hasOwn(role, row.role) ? role[row.role]! : row.role]
    : [row.ref, Object.hasOwn(role, row.role) ? role[row.role]! : row.role, facts.join("|")];
}

const SAFE_DESCRIPTION_MAX_CHARS = 40;
// There is NO description screening on the observation path. Every string a
// page renders — OAuth button copy, an email address, a Gmail subject line, a
// street address, a rendered API key, a card number — is content the driving
// agent needs to read. The only transform left is truncation, which is the
// compactness budget, not masking.
const CARD_SECURITY_VALUE_RE = /\b(?:cvv|cvc|security\s*code)\s*[:#-]?\s*\d{3,4}\b/i;
const PAN_MAX_SPAN_CHARS = 96;

function luhnValid(digits: string): boolean {
  let sum = 0;
  let double = false;
  for (let index = digits.length - 1; index >= 0; index -= 1) {
    let digit = Number(digits[index]);
    if (double) {
      digit *= 2;
      if (digit > 9) digit -= 9;
    }
    sum += digit;
    double = !double;
  }
  return sum % 10 === 0;
}

/** A rendered card number: 13-19 digits in one span that passes Luhn. */
function containsLuhnPan(value: string): boolean {
  const positions = Array.from(value.matchAll(/\d/g), (match) => match.index);
  for (let start = 0; start + 13 <= positions.length; start += 1) {
    const maxLength = Math.min(19, positions.length - start);
    for (let length = 13; length <= maxLength; length += 1) {
      const span = positions.slice(start, start + length);
      if (span[span.length - 1]! - span[0]! + 1 > PAN_MAX_SPAN_CHARS) break;
      if (luhnValid(span.map((position) => value[position]).join(""))) return true;
    }
  }
  return false;
}

/**
 * Card material, used ONLY by the recordable-token screen below (the operator's
 * stderr audit trail and the action trace a capture publishes to the SHARED
 * skill registry). It is never applied to what the agent is shown.
 */
function carriesPaymentMaterial(value: string): boolean {
  return containsLuhnPan(value) || CARD_SECURITY_VALUE_RE.test(value);
}

