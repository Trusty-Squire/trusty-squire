export function compactV2PayloadWithinBudget(payload: unknown): boolean {
  const bytes = Buffer.byteLength(JSON.stringify(payload), "utf8");
  return bytes <= OBSERVE_V2_MAX_WIRE_BYTES && bytes <= OBSERVE_V2_MAX_TOKENS;
}

