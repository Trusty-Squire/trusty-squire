export function safePageSemanticsV2(
  source: ObservationSemanticSourceV2,
  knownSecrets: readonly string[] = [],
): SafePageSemanticsV2 {
  const title = safeDescriptionV2(source.title, knownSecrets);
  const headings = source.headings
    .map((heading) => safeDescriptionV2(heading, knownSecrets))
    .filter((value): value is string => value !== undefined)
    .filter((value, index, all) => all.indexOf(value) === index)
    .slice(0, 1);
  return {
    ...(title === undefined ? {} : { title }),
    ...(headings.length === 0 ? {} : { headings }),
  };
}

export interface SafeObservationDeltaV2 {
  added: SafeControlV2[];
  changed: SafeControlV2[];
  removed: string[];
  stageChanged: boolean;
}

/**
 * Diff only the sealed representation.  In particular, raw changes to a
 * field value, card number, live region, or merchant copy cannot cause either
 * the raw data or a page-derived derivative to cross into the delta.
 */
export function diffSafeControlsV2(
  previous: SafeObservationBaselineV2,
  stage: SafeStageV2,
  rows: readonly SafeControlV2[],
): SafeObservationDeltaV2 {
  const current = new Map(rows.map((row) => [row.ref, row]));
  const added: SafeControlV2[] = [];
  const changed: SafeControlV2[] = [];
  for (const row of rows) {
    const before = previous.byRef.get(row.ref);
    if (before === undefined) added.push(row);
    else if (JSON.stringify(wireControl(before)) !== JSON.stringify(wireControl(row)))
      changed.push(row);
  }
  const removed = [...previous.byRef.keys()].filter((ref) => !current.has(ref));
  return { added, changed, removed, stageChanged: previous.stage !== stage };
}

/**
 * Encodes a structural V2 delta. `null` deliberately asks the caller to send
 * a paged full resync instead: a delta must never exceed the hard wire budget.
 */
export function encodeV2Delta(args: {
  sessionId: string;
  stage: SafeStageV2;
  /** Only the screened origin reaches the wire; paths and query strings stay private. */
  pageUrl?: string;
  semantics?: SafePageSemanticsV2 | undefined;
  delta: SafeObservationDeltaV2;
}): Record<string, unknown> | null {
  const payload: Record<string, unknown> = {
    format: "compact-v2",
    url: safeOriginV2(args.pageUrl) ?? "",
    text: "",
    session_id: args.sessionId,
    delta: true,
    ...(args.semantics === undefined ? {} : { semantic: args.semantics }),
    ...(args.delta.stageChanged ? { stage: args.stage } : {}),
    // `safe_table` follows the established TS delta protocol: rows are
    // upserts, irrespective of whether their ref is new or changed. This keeps
    // existing delta consumers compatible while the @e: map itself stays V2.
    ...(args.delta.added.length + args.delta.changed.length > 0
      ? { safe_table: [...args.delta.added, ...args.delta.changed].map(wireControl) }
      : {}),
    ...(args.delta.removed.length > 0 ? { removed: args.delta.removed } : {}),
  };
  return compactV2PayloadWithinBudget(payload) ? payload : null;
}

const INTENTS: ReadonlyArray<[SafeIntentV2, RegExp]> = [
  ["add_to_cart", /add\s+(?:to\s+)?(?:cart|bag|basket)/i],
  ["view_cart", /view\s+(?:cart|bag|basket)/i],
  ["destructive", /\b(?:delete|remove|erase|destroy)\b/i],
  ["checkout", /^(?:(?:go|proceed|continue)(?:\s+to)?\s+)?(?:secure\s+)?checkout(?:\s+now)?$/i],
  ["payment", /\b(?:pay(?:ment)?|card)\b/i],
  ["signup", /sign\s*up|create\s+(?:account|workspace)|register/i],
  ["login", /log\s*in|sign\s*in|continue\s+with/i],
  ["search", /search|find/i],
  ["close", /close|dismiss|cancel|no\s+thanks/i],
  ["next", /next/i],
  ["previous", /previous|back/i],
  ["submit", /submit|save|create|send/i],
  ["continue", /continue|proceed|start|accept|allow|keep|retain/i],
];

const BUTTON_INPUT_TYPES = new Set(["button", "submit", "reset", "image"]);

function isButtonInput(el: InteractiveElement): boolean {
  return el.tag === "input" && BUTTON_INPUT_TYPES.has((el.type ?? "").toLowerCase());
}

function controlNamingTexts(el: InteractiveElement): Array<string | null | undefined> {
  return [
    el.visibleText,
    el.labelText,
    el.ariaLabel,
    el.iconLabel,
    el.title,
    el.placeholder,
    isButtonInput(el) ? el.value : undefined,
  ];
}

function candidateTexts(el: InteractiveElement): string[] {
  return [
    el.visibleText,
    el.labelText,
    el.ariaLabel,
    el.iconLabel,
    el.title,
    el.placeholder,
    el.name,
    el.id,
    ...(isButtonInput(el) ? [el.value] : []),
  ]
    .filter((part): part is string => typeof part === "string")
    .map((part) => part.replace(/[-_]+/g, " ").replace(/\s+/g, " ").trim())
    .filter(Boolean);
}

function candidateText(el: InteractiveElement): string {
  return candidateTexts(el).join(" ");
}

function controlDescription(
  el: InteractiveElement,
  knownSecrets: readonly string[] = [],
): string | undefined {
  // Labels are chosen from visible/accessibility naming sources only. Native
  // button values are names; field values, `name`, and `id` stay excluded.
  return controlNamingTexts(el)
    .map((candidate) => safeDescriptionV2(candidate, knownSecrets))
    .find((candidate) => candidate !== undefined);
}

function privateQueryTokenV2(value: string): string | null {
  const normalized = value.normalize("NFKC").trim().toLowerCase();
  if (
    normalized.length < 1 ||
    normalized.length > 48 ||
    !/^[\p{L}\p{M}\p{N}]{1,48}$/u.test(normalized) ||
    (/^\p{N}+$/u.test(normalized) && normalized.length > 4)
  ) {
    return null;
  }
  return normalized;
}

function privateQueryTermsV2(value: string): string[] | null {
  const normalized = value.normalize("NFKC").trim().toLowerCase();
  if (normalized.length < 1 || normalized.length > 96 || carriesPaymentMaterial(normalized)) {
    return null;
  }
  const rawTerms = normalized.match(/[\p{L}\p{M}\p{N}]{1,48}/gu);
  if (rawTerms === null || rawTerms.length === 0 || rawTerms.length > 6) return null;
  const separators = normalized.replace(/[\p{L}\p{M}\p{N}]{1,48}/gu, "");
  if (!/^[\s&'’+,.!?():/_|-]*$/u.test(separators)) return null;
  const terms = rawTerms.map(privateQueryTokenV2);
  return terms.every((term): term is string => term !== null) ? [...new Set(terms)] : null;
}

export function controlMatchesPrivateQueryV2(
  el: InteractiveElement,
  query: string,
  knownSecrets: readonly string[] = [],
): boolean {
  const needles = privateQueryTermsV2(query);
  if (needles === null) return false;
  // The private match also consults the element's name/id slugs so
  // choice-group members without their own copy — Shopify shipping-rate
  // radios (name "checkout[shipping_rate][id]", id "checkout_shipping_rate_…")
  // — stay queryable. These are DOM identifiers, never field values, and each
  // candidate still passes the full secret-shape gate below before any token
  // comparison.
  return [...controlNamingTexts(el), el.name, el.id].some((candidate) => {
    if (typeof candidate !== "string") return false;
    const normalized = candidate.normalize("NFKC").trim().toLowerCase();
    if (carriesPaymentMaterial(normalized)) return false;
    if (knownSecrets.some((secret) => secret.length > 0 && candidate.includes(secret))) {
      return false;
    }
    const tokens = candidate.normalize("NFKC").match(/[\p{L}\p{M}\p{N}]{1,48}/gu);
    if (tokens === null) return false;
    const safeTokens = new Set(
      tokens.map(privateQueryTokenV2).filter((token): token is string => token !== null),
    );
    return needles.every((needle) => safeTokens.has(needle));
  });
}

function roleOf(el: InteractiveElement): SafeRoleV2 | null {
  const role = (el.role ?? "").toLowerCase();
  const type = (el.type ?? "").toLowerCase();
  if (type === "file") return "file";
  if (isButtonInput(el)) return "button";
  if (type === "checkbox" || role === "checkbox") return "checkbox";
  if (type === "radio" || role === "radio") return "radio";
  if (el.tag === "select" || role === "combobox" || role === "listbox") return "select";
  if (el.tag === "input" || el.tag === "textarea" || role === "textbox") return "textbox";
  if (el.tag === "a" || role === "link") return "link";
  if (role === "tab") return "tab";
  if (role === "menuitem" || role === "option") return "menuitem";
  if (
    el.tag === "button" ||
    role === "button" ||
    (el.topmost !== null && el.topmost !== undefined)
  ) {
    return "button";
  }
  return null;
}

function stateOf(el: InteractiveElement): string | undefined {
  // A compact code-owned bitset: c=checked, u=unchecked, d=disabled,
  // r=required.  It is deliberately not a page-provided string.
  let state = "";
  if (el.checked === true) state += "c";
  else if (el.checked === false) state += "u";
  if (el.disabled === true) state += "d";
  if (el.required === true) state += "r";
  return state || undefined;
}

function intentOf(el: InteractiveElement): SafeIntentV2 | undefined {
  const texts = candidateTexts(el);
  return INTENTS.find(([, expression]) => texts.some((text) => expression.test(text)))?.[0];
}

function hasExplicitPaymentFieldSignal(el: InteractiveElement): boolean {
  const autocomplete = (el.autocomplete ?? "").toLowerCase();
  const text = candidateText(el).toLowerCase();
  return (
    autocomplete
      .trim()
      .split(/\s+/)
      .some((token) => token.startsWith("cc-")) ||
    /\b(?:cvc|cvv|csc|card verification(?: (?:value|number))?|card security code)\b/.test(text) ||
    /\b(?:card number|payment card|credit card|debit card)\b/.test(text)
  );
}

function fieldOf(el: InteractiveElement, paymentContext = false): SafeFieldV2 | undefined {
  const autocomplete = (el.autocomplete ?? "").toLowerCase();
  const autocompleteTokens = new Set(autocomplete.trim().split(/\s+/).filter(Boolean));
  const hasAutocomplete = (...tokens: string[]): boolean =>
    tokens.some((token) => autocompleteTokens.has(token));
  const type = (el.type ?? "").toLowerCase();
  const text = candidateText(el).toLowerCase();
  if (
    hasExplicitPaymentFieldSignal(el) ||
    (paymentContext && /\b(?:security code|cvn|cid)\b/.test(text))
  ) {
    return "payment";
  }
  if (type === "password" || hasAutocomplete("current-password", "new-password")) {
    return "password";
  }
  if (type === "email" || hasAutocomplete("email") || /\be-?mail\b/.test(text)) return "email";
  if (
    type === "tel" ||
    [...autocompleteTokens].some((token) => token === "tel" || token.startsWith("tel-")) ||
    /\b(phone|mobile|telephone)\b/.test(text)
  )
    return "phone";
  if (type === "search" || /\bsearch\b/.test(text)) return "search";
  if (hasAutocomplete("username") || /\b(user ?name|handle)\b/.test(text)) return "username";
  if (/\b(card|payment|cc-)/.test(`${autocomplete} ${text}`)) return "payment";
  if (hasAutocomplete("address-level2") || /\b(city|town)\b/.test(text)) return "city";
  if (hasAutocomplete("address-level1") || /\b(state|province|region)\b/.test(text))
    return "region";
  if (hasAutocomplete("postal-code") || /\b(zip|postal)\b/.test(text)) return "postal";
  if (hasAutocomplete("country", "country-name") || /\bcountry\b/.test(text)) return "country";
  // `address-line2` is the optional apartment/suite field in the HTML
  // autocomplete vocabulary. Shopify renders it directly below a required
  // Places-backed `address-line1` combobox. Treating both as `address` makes
  // the compact action map advertise two interchangeable street fields, and a
  // caller can put the delivery address in the apartment field instead. Keep
  // `address` reserved for the required street-address / line-1 control; the
  // optional secondary line is intentionally not a checkout fill target.
  if (
    hasAutocomplete("address-line2", "address-line3") ||
    /\b(?:apartment|apt\.?|suite|unit|floor|building)\b/.test(text) ||
    /\boptional\b/.test(text)
  )
    return undefined;
  if (hasAutocomplete("street-address", "address-line1") || /\b(address|street)\b/.test(text))
    return "address";
  if (
    type === "date" ||
    [...autocompleteTokens].some((token) => token.startsWith("bday")) ||
    /\bdate\b/.test(text)
  )
    return "date";
  if (/\b(quantity|qty)\b/.test(text)) return "quantity";
  if (/\b(promo|coupon|discount)\b/.test(text)) return "promo";
  if (
    [...autocompleteTokens].some((token) => token === "name" || token.endsWith("-name")) ||
    /\b(full )?name\b/.test(text)
  )
    return "name";
  return undefined;
}

/** A code-owned page-stage enum; it never forwards the URL or page copy. */
export function safeStageV2(url: string, elements: readonly InteractiveElement[]): SafeStageV2 {
  let pathname = "";
  try {
    pathname = decodeURIComponent(new URL(url).pathname).toLowerCase();
  } catch {}
  if (
    /(?:^|\/)(?:success|complete|thank-you|thank_you|finished|done)(?:\.(?:php|html?))?(?:\/|$)/.test(
      pathname,
    )
  ) {
    return "complete";
  }
  const actionableElements = elements.filter(
    (element) => element.visible === true && element.topmost !== false,
  );
  const routeStage = checkoutStageFromUrlV2(url);
  const paymentContext =
    routeStage !== null ||
    actionableElements.some((element) => hasExplicitPaymentFieldSignal(element));
  const checkoutFields = new Set<SafeFieldV2>([
    "address",
    "city",
    "region",
    "postal",
    "country",
    "payment",
  ]);
  const hasCheckoutField = actionableElements.some((el) => {
    const role = roleOf(el);
    const field = fieldOf(el, paymentContext);
    return (
      (role === "textbox" || role === "select") && field !== undefined && checkoutFields.has(field)
    );
  });
  const authFields = actionableElements.filter((el) => {
    const role = roleOf(el);
    if (role !== "textbox" && role !== "select") return false;
    const field = fieldOf(el, paymentContext);
    return field === "email" || field === "username" || field === "password";
  });
  const hasPasswordField = authFields.some((el) => fieldOf(el, paymentContext) === "password");
  const hasScopedAuthForm = actionableElements.some((el) => {
    if (roleOf(el) !== "button" || (intentOf(el) !== "login" && intentOf(el) !== "signup")) {
      return false;
    }
    const ownerId = el.formId ?? el.containerId;
    const framePath = el.framePath ?? null;
    return (
      ownerId !== undefined &&
      ownerId !== null &&
      authFields.some(
        (field) =>
          (field.formId ?? field.containerId) === ownerId &&
          (field.framePath ?? null) === framePath,
      )
    );
  });
  if (hasPasswordField || hasScopedAuthForm) return "auth";
  if (routeStage !== null) return routeStage;
  const hasPaymentField = actionableElements.some((el) => {
    const role = roleOf(el);
    return (role === "textbox" || role === "select") && fieldOf(el, paymentContext) === "payment";
  });
  const hasCheckoutAction = actionableElements.some(
    (el) => roleOf(el) === "button" && intentOf(el) === "checkout",
  );
  if (hasPaymentField || (hasCheckoutAction && hasCheckoutField)) return "checkout";
  if (actionableElements.some((el) => intentOf(el) === "add_to_cart")) return "browse";
  if (actionableElements.some((el) => roleOf(el) === "textbox" || roleOf(el) === "select"))
    return "form";
  return "browse";
}

export function checkoutStageFromUrlV2(url: string): "cart" | "checkout" | null {
  let pathname = "";
  try {
    pathname = decodeURIComponent(new URL(url).pathname).toLowerCase();
  } catch {
    return null;
  }
  if (
    /(?:^|\/)(?:checkout|secure[-_]?checkout|payment|order[-_]?review|order\/review)(?:\.(?:php|html?))?(?:\/|$)/i.test(
      pathname,
    )
  ) {
    return "checkout";
  }
  if (
    /(?:^|\/)(?:cart|shopping[-_]?cart|view[-_]?cart|basket|bag)(?:\.(?:php|html?))?(?:\/|$)/i.test(
      pathname,
    )
  ) {
    return "cart";
  }
  return null;
}

function frameOf(el: InteractiveElement, pageOrigin: string): SafeControlV2["frame"] {
  if (el.frameOrigin === null || el.frameOrigin === undefined) return "main";
  return el.frameOrigin === pageOrigin ? "same_origin" : "cross_origin";
}

export function buildSafeControlsV2(args: {
  elements: readonly InteractiveElement[];
  legacyRefs: ReadonlyMap<InteractiveElement, string>;
  /** Durable per-element handles, minted by the session (document-scoped). */
  handles: ReadonlyMap<InteractiveElement, string>;
  pageOrigin: string;
  pageUrl?: string;
  /** Operator-injected vault values, screened out of every description. */
  knownSecrets?: readonly string[];
}): { rows: SafeControlV2[]; byRef: Map<string, string> } {
  const rows: Array<{
    ref: string;
    legacy: string;
    row: Omit<SafeControlV2, "ref">;
    priority: number;
  }> = [];
  const paymentContext =
    checkoutStageFromUrlV2(args.pageUrl ?? "") !== null ||
    args.elements.some((element) => hasExplicitPaymentFieldSignal(element));
  for (const el of args.elements) {
    if (el.visible !== true || el.topmost === false) continue;
    const role = roleOf(el);
    const legacy = args.legacyRefs.get(el);
    const ref = args.handles.get(el);
    if (role === null || legacy === undefined || ref === undefined) continue;
    const state = stateOf(el);
    const action = intentOf(el);
    const field = fieldOf(el, paymentContext);
    const cardChoice = el.cardRadioGroup;
    // Native TypeScript port of browse-use's compact DOM formatting: the
    // already CDP-derived interactive inventory supplies each visible control's
    // descendant/accessibility name. This pass binds that name to its own live
    // element, so no cross-serializer tag/role fallback can swap labels.
    const label = controlLabelV2(controlDescription(el, args.knownSecrets ?? []));
    const row: Omit<SafeControlV2, "ref"> = {
      role,
      visibility: el.inViewport ? "viewport" : "near",
      frame: frameOf(el, args.pageOrigin),
      ...(state === undefined ? {} : { state }),
      ...(action === undefined ? {} : { action }),
      ...(field === undefined ? {} : { field }),
      ...(label === undefined ? {} : { label }),
      ...(cardChoice === null || cardChoice === undefined
        ? {}
        : { choice: `${cardChoice.position}/${cardChoice.total}` }),
    };
    // A signup/login action is the useful first move on a landing page. Put it
    // ahead of unlabeled navigation chrome while preserving the existing
    // viewport and role ordering within each group.
    const actionPriority = action === "signup" ? -20 : action === "login" ? -10 : 0;
    rows.push({
      ref,
      legacy,
      row,
      priority: actionPriority + (el.inViewport ? 0 : 10) + (role === "button" ? 0 : 1),
    });
  }
  rows.sort((a, b) => a.priority - b.priority || a.legacy.localeCompare(b.legacy));
  const byRef = new Map<string, string>();
  const safeRows = rows.map(({ ref, legacy, row }) => {
    byRef.set(ref, legacy);
    return { ref, ...row };
  });
  return { rows: safeRows, byRef };
}

export function encodeV2Page(args: {
  sessionId: string;
  stage: SafeStageV2;
  /** Only the screened origin reaches the wire; paths and query strings stay private. */
  pageUrl?: string;
  semantics?: SafePageSemanticsV2;
  rows: readonly SafeControlV2[];
  cursorFor: (offset: number) => string;
  offset?: number;
  unchanged?: boolean;
  startMetadata?: {
    hint?: string;
    userEmail?: string;
    hintOverflow?: { remaining: number; next_cursor: string };
  };
}): { payload: Record<string, unknown>; nextOffset: number } {
  const offset = args.offset ?? 0;
  if (args.unchanged === true && offset === 0) {
    const payload: Record<string, unknown> = {
      format: "compact-v2",
      url: safeOriginV2(args.pageUrl) ?? "",
      text: "",
      session_id: args.sessionId,
      stage: args.stage,
      ...(args.startMetadata?.hint === undefined ? {} : { hint: args.startMetadata.hint }),
      ...(args.startMetadata?.userEmail === undefined
        ? {}
        : { user_email: args.startMetadata.userEmail }),
      ...(args.startMetadata?.hintOverflow === undefined
        ? {}
        : { hint_overflow: args.startMetadata.hintOverflow }),
      ...(args.semantics === undefined || Object.keys(args.semantics).length === 0
        ? {}
        : { semantic: args.semantics }),
      delta: true,
    };
    if (!compactV2PayloadWithinBudget(payload)) {
      throw new Error("compact-v2 budget metadata exceeded");
    }
    return {
      payload,
      nextOffset: 0,
    };
  }
  const visible: WireControlV2[] = [];
  // Initial observations stay decisively small. Overflow is retrieved through
  // the in-MCP query cursor, never a shell-readable snapshot file.
  const pageEnd =
    offset === 0 ? Math.min(args.rows.length, FIRST_PAGE_ROW_LIMIT) : args.rows.length;
  for (let index = offset; index < pageEnd; index += 1) {
    const candidate = args.rows[index]!;
    const remainder = args.rows.length - (index + 1);
    const payload: Record<string, unknown> = {
      format: "compact-v2",
      url: safeOriginV2(args.pageUrl) ?? "",
      text: "",
      session_id: args.sessionId,
      stage: args.stage,
      ...(args.startMetadata?.hint === undefined ? {} : { hint: args.startMetadata.hint }),
      ...(args.startMetadata?.userEmail === undefined
        ? {}
        : { user_email: args.startMetadata.userEmail }),
      ...(args.startMetadata?.hintOverflow === undefined
        ? {}
        : { hint_overflow: args.startMetadata.hintOverflow }),
      ...(args.semantics === undefined || Object.keys(args.semantics).length === 0
        ? {}
        : { semantic: args.semantics }),
      safe_table: [...visible, wireControl(candidate)],
      ...(remainder > 0
        ? { overflow: { remaining: remainder, next_cursor: args.cursorFor(index + 1) } }
        : {}),
    };
    if (!compactV2PayloadWithinBudget(payload)) break;
    visible.push(wireControl(candidate));
  }
  const nextOffset = offset + visible.length;
  const remaining = args.rows.length - nextOffset;
  const payload: Record<string, unknown> = {
    format: "compact-v2",
    url: safeOriginV2(args.pageUrl) ?? "",
    text: "",
    session_id: args.sessionId,
    stage: args.stage,
    ...(args.startMetadata?.hint === undefined ? {} : { hint: args.startMetadata.hint }),
    ...(args.startMetadata?.userEmail === undefined
      ? {}
      : { user_email: args.startMetadata.userEmail }),
    ...(args.startMetadata?.hintOverflow === undefined
      ? {}
      : { hint_overflow: args.startMetadata.hintOverflow }),
    ...(args.semantics === undefined || Object.keys(args.semantics).length === 0
      ? {}
      : { semantic: args.semantics }),
    safe_table: visible,
    ...(remaining > 0 ? { overflow: { remaining, next_cursor: args.cursorFor(nextOffset) } } : {}),
  };
  // The fixed fields are deliberately tiny, so failure means a hostilely long
  // session id/cursor. Fail closed rather than exceeding the wire contract.
  if (!compactV2PayloadWithinBudget(payload)) {
    throw new Error("compact-v2 budget metadata exceeded");
  }
  return { payload, nextOffset };
}
