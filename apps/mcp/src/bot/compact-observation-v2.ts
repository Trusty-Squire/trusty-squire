function controlLabelNamingTexts(el: InteractiveElement): Array<string | null | undefined> {
  const role = roleOf(el);
  const names = el.compactNames;
  if (names) {
    const accessibleName = normalizeDescriptionV2(names.accessibleName);
    const visibleText = normalizeDescriptionV2(names.visibleText);
    const iconLabel = normalizeDescriptionV2(names.iconLabel);
    const aggregateIconName =
      visibleText !== undefined &&
      iconLabel !== undefined &&
      accessibleName === `${iconLabel} ${visibleText}`;
    return [
      aggregateIconName ? undefined : names.accessibleName,
      names.ariaLabel,
      names.labelledByText,
      names.labelText,
      (el.type ?? "").toLowerCase() === "image" ? names.alt : undefined,
      names.visibleText,
      isButtonInput(el) ? names.value : undefined,
      names.iconLabel,
      names.title,
      role === "textbox" ? names.placeholder : undefined,
      role === "textbox" ? names.name : undefined,
    ];
  }
  return [
    el.ariaLabel,
    el.labelText,
    el.visibleText,
    isButtonInput(el) ? el.value : undefined,
    el.iconLabel,
    el.title,
    role === "textbox" ? el.placeholder : undefined,
    role === "textbox" ? el.name : undefined,
  ];
}

function candidateTexts(el: InteractiveElement): string[] {
  return [
    el.visibleText,
    el.labelText,
    el.ariaLabel,
    el.iconLabel,
    el.title,
    el.placeholder,
    el.name,
    el.id,
    ...(isButtonInput(el) ? [el.value] : []),
  ]
    .filter((part): part is string => typeof part === "string")
    .map((part) => part.replace(/[-_]+/g, " ").replace(/\s+/g, " ").trim())
    .filter(Boolean);
}

function candidateText(el: InteractiveElement): string {
  return candidateTexts(el).join(" ");
}

function controlDescription(el: InteractiveElement, role: SafeRoleV2): string {
  // Prefer authored accessibility names over descendant text. Navigation
  // toggles and data-row controls often contain an entire menu/card subtree;
  // choosing textContent first turned their concise aria/label name into a
  // mashed-together alias. Native button values are names, while field values
  // and ids remain excluded. Textbox placeholder/name are useful only after
  // the genuine accessibility and visible-name sources have been exhausted.
  const chosen = controlLabelNamingTexts(el)
    .map((candidate) => normalizeDescriptionV2(candidate))
    .find((candidate) => candidate !== undefined);
  if (chosen !== undefined) {
    // Add the page's region context to otherwise opaque labels (such as @as15169).
    const context = regionContextV2(
      el.compactNames ? el.compactNames.container : el.container,
      chosen,
    );
    const description = context === undefined ? chosen : `${chosen} ${context}`;
    if (controlLabelV2(description) !== undefined) return description;
  }
  // Every actionable row still needs a human-usable alias. The nearest
  // semantic region is the best available immediate context; a genuinely
  // anonymous control falls back to its role rather than becoming a bare
  // [ref, role] tuple. This is descriptive only and does not alter identity.
  const context = namedContainerContextV2(
    el.compactNames ? el.compactNames.container : el.container,
  );
  return context === undefined ? `${role} ${el.index + 1}` : `${context} ${role}`;
}

/** A description is "uninformative" when it carries no 3+-letter word run: ids, short codes, hex fragments. */
function isUninformativeDescriptionV2(description: string): boolean {
  return (
    !/[a-zA-Z]{3,}/.test(description) &&
    !Array.from(description).some(
      (character) => character.charCodeAt(0) > 0x7f && /\p{L}/u.test(character),
    )
  );
}

function regionContextV2(container: string | null | undefined, chosen: string): string | undefined {
  if (container === null || container === undefined) return undefined;
  if (!isUninformativeDescriptionV2(chosen)) return undefined;
  const context = namedContainerContextV2(container);
  if (context === undefined) return undefined;
  return context.slice(0, 24).replace(/-+$/, "") || undefined;
}

function namedContainerContextV2(container: string | null | undefined): string | undefined {
  if (container === null || container === undefined) return undefined;
  const separator = container.indexOf(":");
  const kind = separator < 0 ? undefined : container.slice(0, separator).toLowerCase();
  const raw = separator < 0 ? container : container.slice(separator + 1);
  const context = safeDescriptionV2(raw.replace(/[-_]+/g, " "));
  return context === undefined || context.toLowerCase() === kind ? undefined : context;
}

function privateQueryTokenV2(value: string): string | null {
  const normalized = value.normalize("NFKC").trim().toLowerCase();
  if (
    normalized.length < 1 ||
    normalized.length > 48 ||
    !/^[\p{L}\p{M}\p{N}]{1,48}$/u.test(normalized)
  ) {
    return null;
  }
  return normalized;
}

function privateQueryTermsV2(value: string): string[] | null {
  const normalized = value.normalize("NFKC").trim().toLowerCase();
  if (normalized.length < 1 || normalized.length > 96) return null;
  const rawTerms = normalized.match(/[\p{L}\p{M}\p{N}]{1,48}/gu);
  if (rawTerms === null || rawTerms.length === 0 || rawTerms.length > 6) return null;
  const separators = normalized.replace(/[\p{L}\p{M}\p{N}]{1,48}/gu, "");
  if (!/^[\s&'’+,.!?():/_|-]*$/u.test(separators)) return null;
  const terms = rawTerms.map(privateQueryTokenV2);
  return terms.every((term): term is string => term !== null) ? [...new Set(terms)] : null;
}

export function controlQueryMatchV2(
  el: InteractiveElement,
  query: string,
): { rank: number; provenance: SafeQueryMatchV2 } | null {
  const needles = privateQueryTermsV2(query);
  if (needles === null) return null;
  const phrase = (value: string | null | undefined): string | null => {
    if (!value) return null;
    const terms = privateQueryTermsV2(value);
    return terms === null ? null : terms.join(" ");
  };
  const queryPhrase = needles.join(" ");
  const names = el.compactNames;
  const accessibleNames = names
    ? [
        names.accessibleName,
        names.ariaLabel,
        names.labelledByText,
        ["button", "input", "select", "textarea"].includes(el.tag) ? names.labelText : null,
      ]
    : [el.ariaLabel, el.labelText];
  if (accessibleNames.some((candidate) => phrase(candidate) === queryPhrase)) {
    return { rank: 0, provenance: "name" };
  }
  const role = roleOf(el);
  const roleWords =
    role === "select" ? ["select", "dropdown", "combobox"] : role === null ? [] : [role];
  if (needles.length === 1 && roleWords.includes(needles[0]!)) {
    return { rank: 1, provenance: "role" };
  }
  // AND-match every term against this control's own name/text/DOM metadata.
  // Ancestor/page text is excluded, so a page root or sidebar cannot lend its
  // name to every descendant action.
  const localCandidates: Array<string | null | undefined> = [
    ...controlNamingTexts(el),
    el.name,
    el.id,
    ...roleWords,
  ];
  const combined = new Set<string>();
  for (const candidate of localCandidates) {
    if (typeof candidate !== "string" || candidate.length === 0) continue;
    const tokens = candidate.normalize("NFKC").match(/[\p{L}\p{M}\p{N}]{1,48}/gu);
    if (tokens === null) continue;
    for (const token of tokens) {
      const safe = privateQueryTokenV2(token);
      if (safe !== null) combined.add(safe);
    }
  }
  if (needles.every((needle) => combined.has(needle))) {
    return { rank: 2, provenance: "text" };
  }
  const container = names?.container ?? el.container;
  const separator = container?.indexOf(":") ?? -1;
  const kind = separator < 0 ? "" : container!.slice(0, separator).toLowerCase();
  // Explicit form/dialog ownership is local enough to be useful. Broad main,
  // navigation and section copy is not query authority.
  if (["form", "fieldset", "dialog"].includes(kind)) {
    const contextTerms = privateQueryTermsV2(container!.slice(separator + 1));
    if (contextTerms !== null) {
      const context = new Set(contextTerms);
      if (needles.every((needle) => context.has(needle))) {
        return { rank: 3, provenance: "context" };
      }
    }
  }
  return null;
}

export function controlMatchesPrivateQueryV2(el: InteractiveElement, query: string): boolean {
  return controlQueryMatchV2(el, query) !== null;
}

function roleOf(el: InteractiveElement): SafeRoleV2 | null {
  const role = (el.role ?? "").toLowerCase();
  const type = (el.type ?? "").toLowerCase();
  if (type === "file") return "file";
  if (isButtonInput(el)) return "button";
  if (type === "checkbox" || role === "checkbox") return "checkbox";
  if (type === "radio" || role === "radio") return "radio";
  if (el.tag === "select" || role === "combobox" || role === "listbox") return "select";
  if (el.tag === "input" || el.tag === "textarea" || role === "textbox") return "textbox";
  if (el.tag === "a" || role === "link") return "link";
  if (role === "tab") return "tab";
  if (role === "menuitem" || role === "option") return "menuitem";
  if (el.tag === "button" || role === "button") {
    return "button";
  }
  return role || null;
}

function stateOf(el: InteractiveElement): string | undefined {
  // A compact code-owned bitset: c=checked, u=unchecked, d=disabled,
  // r=required.  It is deliberately not a page-provided string.
  let state = "";
  if (el.checked === true) state += "c";
  else if (el.checked === false) state += "u";
  if (el.disabled === true) state += "d";
  if (el.required === true) state += "r";
  return state || undefined;
}

function intentOf(el: InteractiveElement): SafeIntentV2 | undefined {
  const texts = candidateTexts(el);
  return INTENTS.find(([, expression]) => texts.some((text) => expression.test(text)))?.[0];
}

function hasExplicitPaymentFieldSignal(el: InteractiveElement): boolean {
  const autocomplete = (el.autocomplete ?? "").toLowerCase();
  const text = candidateText(el).toLowerCase();
  return (
    autocomplete
      .trim()
      .split(/\s+/)
      .some((token) => token.startsWith("cc-")) ||
    /\b(?:cvc|cvv|csc|card verification(?: (?:value|number))?|card security code)\b/.test(text) ||
    /\b(?:card number|payment card|credit card|debit card)\b/.test(text)
  );
}

function fieldOf(el: InteractiveElement, paymentContext = false): SafeFieldV2 | undefined {
  const autocomplete = (el.autocomplete ?? "").toLowerCase();
  const autocompleteTokens = new Set(autocomplete.trim().split(/\s+/).filter(Boolean));
  const hasAutocomplete = (...tokens: string[]): boolean =>
    tokens.some((token) => autocompleteTokens.has(token));
  const type = (el.type ?? "").toLowerCase();
  const text = candidateText(el).toLowerCase();
  if (
    hasExplicitPaymentFieldSignal(el) ||
    (paymentContext && /\b(?:security code|cvn|cid)\b/.test(text))
  ) {
    return "payment";
  }
  if (type === "password" || hasAutocomplete("current-password", "new-password")) {
    return "password";
  }
  if (type === "email" || hasAutocomplete("email") || /\be-?mail\b/.test(text)) return "email";
  if (
    type === "tel" ||
    [...autocompleteTokens].some((token) => token === "tel" || token.startsWith("tel-")) ||
    /\b(phone|mobile|telephone)\b/.test(text)
  )
    return "phone";
  if (type === "search" || /\bsearch\b/.test(text)) return "search";
  if (hasAutocomplete("username") || /\b(user ?name|handle)\b/.test(text)) return "username";
  if (/\b(card|payment|cc-)/.test(`${autocomplete} ${text}`)) return "payment";
  if (hasAutocomplete("address-level2") || /\b(city|town)\b/.test(text)) return "city";
  if (hasAutocomplete("address-level1") || /\b(state|province|region)\b/.test(text))
    return "region";
  if (hasAutocomplete("postal-code") || /\b(zip|postal)\b/.test(text)) return "postal";
  if (hasAutocomplete("country", "country-name") || /\bcountry\b/.test(text)) return "country";
  // `address-line2` is the optional apartment/suite field in the HTML
  // autocomplete vocabulary. Shopify renders it directly below a required
  // Places-backed `address-line1` combobox. Treating both as `address` makes
  // the compact action map advertise two interchangeable street fields, and a
  // caller can put the delivery address in the apartment field instead. Keep
  // `address` reserved for the required street-address / line-1 control; the
  // optional secondary line is intentionally not a checkout fill target.
  if (
    hasAutocomplete("address-line2", "address-line3") ||
    /\b(?:apartment|apt\.?|suite|unit|floor|building)\b/.test(text) ||
    /\boptional\b/.test(text)
  )
    return undefined;
  if (hasAutocomplete("street-address", "address-line1") || /\b(address|street)\b/.test(text))
    return "address";
  if (
    type === "date" ||
    [...autocompleteTokens].some((token) => token.startsWith("bday")) ||
    /\bdate\b/.test(text)
  )
    return "date";
  if (/\b(quantity|qty)\b/.test(text)) return "quantity";
  if (/\b(promo|coupon|discount)\b/.test(text)) return "promo";
  if (
    [...autocompleteTokens].some((token) => token === "name" || token.endsWith("-name")) ||
    /\b(full )?name\b/.test(text)
  )
    return "name";
  return undefined;
}

/** A code-owned page-stage enum; it never forwards the URL or page copy. */
export function safeStageV2(url: string, elements: readonly InteractiveElement[]): SafeStageV2 {
  let pathname = "";
  try {
    pathname = decodeURIComponent(new URL(url).pathname).toLowerCase();
  } catch {}
  if (
    /(?:^|\/)(?:success|complete|thank-you|thank_you|finished|done)(?:\.(?:php|html?))?(?:\/|$)/.test(
      pathname,
    )
  ) {
    return "complete";
  }
  const actionableElements = elements.filter(
    (element) => element.visible === true && element.topmost !== false,
  );
  const routeStage = checkoutStageFromUrlV2(url);
  const paymentContext =
    routeStage !== null ||
    actionableElements.some((element) => hasExplicitPaymentFieldSignal(element));
  const checkoutFields = new Set<SafeFieldV2>([
    "address",
    "city",
    "region",
    "postal",
    "country",
    "payment",
  ]);
  const hasCheckoutField = actionableElements.some((el) => {
    const role = roleOf(el);
    const field = fieldOf(el, paymentContext);
    return (
      (role === "textbox" || role === "select") && field !== undefined && checkoutFields.has(field)
    );
  });
  const authFields = actionableElements.filter((el) => {
    const role = roleOf(el);
    if (role !== "textbox" && role !== "select") return false;
    const field = fieldOf(el, paymentContext);
    return field === "email" || field === "username" || field === "password";
  });
  const hasPasswordField = authFields.some((el) => fieldOf(el, paymentContext) === "password");
  const authRoute =
    /(?:^|\/)(?:login|log-in|signin|sign-in|signup|sign-up|register|auth)(?:\.(?:php|html?))?(?:\/|$)/.test(
      pathname,
    );
  const hasScopedAuthForm = actionableElements.some((el) => {
    if (roleOf(el) !== "button" || (intentOf(el) !== "login" && intentOf(el) !== "signup")) {
      return false;
    }
    const ownerId = el.formId ?? el.containerId;
    const framePath = el.framePath ?? null;
    return (
      ownerId !== undefined &&
      ownerId !== null &&
      authFields.some(
        (field) =>
          (field.formId ?? field.containerId) === ownerId &&
          (field.framePath ?? null) === framePath,
      )
    );
  });
  // A password editor on an authenticated settings page is a form, not proof
  // that the whole document is a login surface. Require a local login/signup
  // submit owner, or an auth route plus an auth field.
  if (hasScopedAuthForm || (authRoute && (hasPasswordField || authFields.length > 0)))
    return "auth";
  if (routeStage !== null) return routeStage;
  const hasPaymentField = actionableElements.some((el) => {
    const role = roleOf(el);
    return (role === "textbox" || role === "select") && fieldOf(el, paymentContext) === "payment";
  });
  const hasCheckoutAction = actionableElements.some(
    (el) => roleOf(el) === "button" && intentOf(el) === "checkout",
  );
  if (hasPaymentField || (hasCheckoutAction && hasCheckoutField)) return "checkout";
  if (actionableElements.some((el) => intentOf(el) === "add_to_cart")) return "browse";
  if (actionableElements.some((el) => roleOf(el) === "textbox" || roleOf(el) === "select"))
    return "form";
  return "browse";
}

export function checkoutStageFromUrlV2(url: string): "cart" | "checkout" | null {
  let pathname = "";
  try {
    pathname = decodeURIComponent(new URL(url).pathname).toLowerCase();
  } catch {
    return null;
  }
  if (
    /(?:^|\/)(?:checkout|secure[-_]?checkout|payment|order[-_]?review|order\/review)(?:\.(?:php|html?))?(?:\/|$)/i.test(
      pathname,
    )
  ) {
    return "checkout";
  }
  if (
    /(?:^|\/)(?:cart|shopping[-_]?cart|view[-_]?cart|basket|bag)(?:\.(?:php|html?))?(?:\/|$)/i.test(
      pathname,
    )
  ) {
    return "cart";
  }
  return null;
}

function frameOf(el: InteractiveElement, pageOrigin: string): SafeControlV2["frame"] {
  if (el.frameOrigin === null || el.frameOrigin === undefined) return "main";
  return el.frameOrigin === pageOrigin ? "same_origin" : "cross_origin";
}

/**
 * Deterministically disambiguate duplicate labels within one snapshot. The
 * /dashboard/token dogfood returned two distinct rows both labelled
 * `@curl-example` with nothing to tell them apart — a correct pick was a coin
 * flip. The first occurrence keeps the plain label; the second and later
 * occurrences get a stable ordinal suffix (`@curl-example-2`, `-3`, …)
 * following the map's own row order, so the same page always yields the same
 * numbering. A suffix that would collide with an existing label (the page
 * itself rendering "curl example 2" alongside two "curl example" rows) is
 * skipped, so disambiguation never mints a new ambiguity.
 */
export function disambiguateDuplicateLabelsV2(
  labels: readonly (string | undefined)[],
): Array<string | undefined> {
  const occurrences = new Map<string, number>();
  for (const label of labels) {
    if (label === undefined) continue;
    occurrences.set(label, (occurrences.get(label) ?? 0) + 1);
  }
  const assigned = new Set<string>();
  for (const label of labels) if (label !== undefined) assigned.add(label);
  const seen = new Map<string, number>();
  return labels.map((label) => {
    if (label === undefined) return undefined;
    const occurrence = (seen.get(label) ?? 0) + 1;
    seen.set(label, occurrence);
    if (occurrence === 1) return label;
    let suffix = occurrence;
    let candidate = labelWithOrdinalV2(label, suffix);
    while (assigned.has(candidate)) {
      suffix += 1;
      candidate = labelWithOrdinalV2(label, suffix);
    }
    assigned.add(candidate);
    return candidate;
  });
}

export function buildSafeControlsV2(args: {
  elements: readonly InteractiveElement[];
  legacyRefs: ReadonlyMap<InteractiveElement, string>;
  /** Durable per-element handles, minted by the session (document-scoped). */
  handles: ReadonlyMap<InteractiveElement, string>;
  pageOrigin: string;
  pageUrl?: string;
  canonical?: boolean;
  anchorLabel?: (ref: string, preferred: string | undefined) => string | undefined;
}): { rows: SafeControlV2[]; byRef: Map<string, string> } {
  const rows: Array<{
    ref: string;
    legacy: string;
    row: Omit<SafeControlV2, "ref">;
    priority: number;
  }> = [];
  const paymentContext =
    checkoutStageFromUrlV2(args.pageUrl ?? "") !== null ||
    args.elements.some((element) => hasExplicitPaymentFieldSignal(element));
  for (const el of args.elements) {
    if (el.visible !== true || (!args.canonical && el.topmost === false)) continue;
    const role = roleOf(el) ?? (args.canonical ? el.role || "generic" : null);
    const legacy = args.legacyRefs.get(el);
    const ref = args.handles.get(el);
    if (role === null || legacy === undefined || ref === undefined) continue;
    const state = stateOf(el);
    const action = intentOf(el);
    const field = fieldOf(el, paymentContext);
    const cardChoice = el.cardRadioGroup;
    // Native TypeScript port of browse-use's compact DOM formatting: the
    // already CDP-derived interactive inventory supplies each visible control's
    // descendant/accessibility name. This pass binds that name to its own live
    // element, so no cross-serializer tag/role fallback can swap labels.
    const label = controlLabelV2(controlDescription(el, role));
    const row: Omit<SafeControlV2, "ref"> = {
      role,
      visibility: el.inViewport ? "viewport" : "near",
      frame: frameOf(el, args.pageOrigin),
      ...(state === undefined ? {} : { state }),
      ...(action === undefined ? {} : { action }),
      ...(field === undefined ? {} : { field }),
      ...(label === undefined ? {} : { label }),
      ...(cardChoice === null || cardChoice === undefined
        ? {}
        : { choice: `${cardChoice.position}/${cardChoice.total}` }),
    };
    // A signup/login action is the useful first move on a landing page. Put it
    // ahead of unlabeled navigation chrome while preserving the existing
    // viewport and role ordering within each group.
    const actionPriority = action === "signup" ? -20 : action === "login" ? -10 : 0;
    rows.push({
      ref,
      legacy,
      row,
      priority: actionPriority + (el.inViewport ? 0 : 10) + (role === "button" ? 0 : 1),
    });
  }
  rows.sort((a, b) => a.priority - b.priority || a.legacy.localeCompare(b.legacy));
  // The legacy fallback disambiguates after final ordering. Compact-v2 supplies
  // anchorLabel instead, reserving each alias for its physical-node capability.
  const disambiguated = disambiguateDuplicateLabelsV2(rows.map(({ row }) => row.label));
  const byRef = new Map<string, string>();
  const safeRows = rows.map(({ ref, legacy, row }, position) => {
    const label = args.anchorLabel ? args.anchorLabel(ref, row.label) : disambiguated[position];
    byRef.set(ref, legacy);
    return { ref, ...row, ...(label === undefined ? {} : { label }) };
  });
  return { rows: safeRows, byRef };
}

export function encodeV2QueryPage(args: {
  sessionId: string;
  stage: SafeStageV2;
  /** The live page URL, path and query included — the agent needs to know where it is. */
  pageUrl?: string;
  semantics?: SafePageSemanticsV2;
  rows: readonly SafeControlV2[];
  cursorFor: (offset: number) => string;
  offset?: number;
  startMetadata?: {
    hint?: string;
    userEmail?: string;
    hintOverflow?: { remaining: number; next_cursor: string };
  };
}): { payload: Record<string, unknown>; nextOffset: number } {
  const offset = args.offset ?? 0;
  let fixed: Record<string, unknown> = {
    format: "browser-use-control-query",
    url: args.pageUrl ?? "",
    session_id: args.sessionId,
    stage: args.stage,
    ...(args.startMetadata?.hint === undefined ? {} : { hint: args.startMetadata.hint }),
    ...(args.startMetadata?.userEmail === undefined
      ? {}
      : { user_email: args.startMetadata.userEmail }),
    ...(args.startMetadata?.hintOverflow === undefined
      ? {}
      : { hint_overflow: args.startMetadata.hintOverflow }),
    ...(args.semantics === undefined || Object.keys(args.semantics).length === 0
      ? {}
      : { semantic: args.semantics }),
  };
  const pageWith = (
    table: readonly WireControlV2[],
    nextOffset: number,
  ): Record<string, unknown> => {
    const remaining = args.rows.length - nextOffset;
    return {
      ...fixed,
      safe_table: table,
      ...(remaining > 0
        ? { overflow: { remaining, next_cursor: args.cursorFor(nextOffset) } }
        : {}),
    };
  };
  if (offset < args.rows.length) {
    const probe = pageWith([wireControl(args.rows[offset]!)], offset + 1);
    if (!compactV2PayloadWithinBudget(probe)) {
      const degraded = compactV2DegradeMetadata(probe);
      if (degraded === null) throw new Error("compact-v2 budget metadata exceeded");
      const degradedFixed = { ...degraded };
      delete degradedFixed.safe_table;
      delete degradedFixed.overflow;
      fixed = degradedFixed;
    }
  }
  const visible: WireControlV2[] = [];
  // Every interactive control is a candidate for the default map: rows are
  // packed in priority order until the wire budget is actually reached, so a
  // below-the-fold primary CTA is never stranded behind an arbitrary row cap
  // (the live Xata failure). Overflow remains reachable through the in-MCP
  // query cursor, never a shell-readable snapshot file.
  let nextOffset = offset;
  for (let index = offset; index < args.rows.length; index += 1) {
    const candidate = wireControl(args.rows[index]!);
    if (!compactV2PayloadWithinBudget(pageWith([...visible, candidate], index + 1))) break;
    visible.push(candidate);
    nextOffset = index + 1;
  }
  if (visible.length === 0 && offset < args.rows.length) {
    // Budget-driven packing must never emit an empty page whose cursor points
    // back at the same offset. Force the first row in and let fixed metadata
    // degrade around it — on a real page this is unreachable.
    visible.push(wireControl(args.rows[offset]!));
    nextOffset = offset + 1;
  }
  let payload = pageWith(visible, nextOffset);
  if (!compactV2PayloadWithinBudget(payload)) {
    // Only hostile fixed metadata (a code-owned session id/cursor) lands here;
    // degrade the metadata before ever dropping an actionable row.
    const degraded = compactV2DegradeMetadata(payload);
    if (degraded === null) throw new Error("compact-v2 budget metadata exceeded");
    payload = degraded;
  }
  return { payload, nextOffset };
}
