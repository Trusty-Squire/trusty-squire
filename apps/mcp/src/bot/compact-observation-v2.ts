import { createHmac } from "node:crypto";
import { Buffer } from "node:buffer";
import type { InteractiveElement } from "./browser.js";

export const OBSERVE_V2_MAX_WIRE_BYTES = 4_096;
export const OBSERVE_V2_MAX_TOKENS = 1_024;
const FIRST_PAGE_ROW_LIMIT = 4;

export type SafeRoleV2 =
  | "button"
  | "link"
  | "textbox"
  | "select"
  | "checkbox"
  | "radio"
  | "tab"
  | "menuitem"
  | "file";
export type SafeIntentV2 =
  | "search"
  | "close"
  | "next"
  | "previous"
  | "submit"
  | "continue"
  | "login"
  | "signup"
  | "add_to_cart"
  | "checkout"
  | "payment";
// These are semantic classes generated by TS, never page-provided labels. They
// make a small action map useful for forms while keeping values, merchant copy,
// live regions, and secrets on the private side of the seal.
export type SafeFieldV2 =
  | "email"
  | "password"
  | "username"
  | "name"
  | "phone"
  | "search"
  | "address"
  | "city"
  | "region"
  | "postal"
  | "country"
  | "date"
  | "quantity"
  | "promo"
  | "payment";
export type SafeStageV2 = "browse" | "auth" | "form" | "cart" | "checkout" | "complete";

export interface SafeControlV2 {
  ref: string;
  role: SafeRoleV2;
  state?: string;
  visibility: "viewport" | "near";
  action?: SafeIntentV2;
  field?: SafeFieldV2;
  choice?: string;
  frame: "main" | "same_origin" | "cross_origin";
}

export interface BrowserUseSelectedNode {
  backend_node_id: number;
  tag: string;
  role: string | null;
  /** Process-internal only. Never copy this into a safe row or a log. */
  name: string;
}

export interface SafeObservationIndexV2 {
  generation: number;
  stage: SafeStageV2;
  rows: SafeControlV2[];
  byRef: Map<string, string>;
  expiresAt: number;
}

type WireControlV2 = [string, string, SafeIntentV2 | null, SafeFieldV2 | null, string?];

// The protocol is intentionally positional to keep repeated observes small.
// Tuple schema: [ref, role(b/l/t/s/c/r/tb/m/f), action|null, field|null,
// optional state/choice]. Every value is either a sealed HMAC ref or a
// code-owned finite token.
function wireControl(row: SafeControlV2): WireControlV2 {
  const role: Record<SafeRoleV2, string> = {
    button: "b",
    link: "l",
    textbox: "t",
    select: "s",
    checkbox: "c",
    radio: "r",
    tab: "tb",
    menuitem: "m",
    file: "f",
  };
  const signal = row.choice ?? row.state;
  return signal === undefined
    ? [row.ref, role[row.role], row.action ?? null, row.field ?? null]
    : [row.ref, role[row.role], row.action ?? null, row.field ?? null, signal];
}

const INTENTS: ReadonlyArray<[SafeIntentV2, RegExp]> = [
  ["add_to_cart", /add\s+(?:to\s+)?(?:cart|bag|basket)/i],
  ["checkout", /checkout|view\s+(?:cart|bag|basket)/i],
  ["payment", /pay(?:ment)?|card/i],
  ["signup", /sign\s*up|create\s+(?:account|workspace)|register/i],
  ["login", /log\s*in|sign\s*in|continue\s+with/i],
  ["search", /search|find/i],
  ["close", /close|dismiss|cancel|no\s+thanks/i],
  ["next", /next/i],
  ["previous", /previous|back/i],
  ["submit", /submit|save|create|send/i],
  ["continue", /continue|proceed|start|accept|allow/i],
];

function candidateText(el: InteractiveElement): string {
  return [
    el.visibleText,
    el.labelText,
    el.ariaLabel,
    el.iconLabel,
    el.title,
    el.placeholder,
    el.name,
    el.id,
  ]
    .filter((part): part is string => typeof part === "string")
    .join(" ");
}

function roleOf(el: InteractiveElement): SafeRoleV2 | null {
  const role = (el.role ?? "").toLowerCase();
  const type = (el.type ?? "").toLowerCase();
  if (type === "file") return "file";
  if (type === "checkbox" || role === "checkbox") return "checkbox";
  if (type === "radio" || role === "radio") return "radio";
  if (el.tag === "select" || role === "combobox" || role === "listbox") return "select";
  if (el.tag === "input" || el.tag === "textarea" || role === "textbox") return "textbox";
  if (el.tag === "a" || role === "link") return "link";
  if (role === "tab") return "tab";
  if (role === "menuitem" || role === "option") return "menuitem";
  if (el.tag === "button" || role === "button" || (el.topmost !== null && el.topmost !== undefined)) {
    return "button";
  }
  return null;
}

function stateOf(el: InteractiveElement): string | undefined {
  // A compact code-owned bitset: c=checked, u=unchecked, d=disabled-ish,
  // r=required.  It is deliberately not a page-provided string.
  let state = "";
  if (el.checked === true) state += "c";
  else if (el.checked === false) state += "u";
  if (el.sealed === true) state += "d";
  return state || undefined;
}

function intentOf(el: InteractiveElement): SafeIntentV2 | undefined {
  const text = candidateText(el);
  return INTENTS.find(([, expression]) => expression.test(text))?.[0];
}

function fieldOf(el: InteractiveElement): SafeFieldV2 | undefined {
  const autocomplete = (el.autocomplete ?? "").toLowerCase();
  const type = (el.type ?? "").toLowerCase();
  const text = candidateText(el).toLowerCase();
  if (type === "password" || autocomplete === "current-password" || autocomplete === "new-password") {
    return "password";
  }
  if (type === "email" || autocomplete === "email" || /\be-?mail\b/.test(text)) return "email";
  if (type === "tel" || autocomplete === "tel" || /\b(phone|mobile|telephone)\b/.test(text)) return "phone";
  if (type === "search" || /\bsearch\b/.test(text)) return "search";
  if (autocomplete === "username" || /\b(user ?name|handle)\b/.test(text)) return "username";
  if (/\b(card|payment|cc-)/.test(`${autocomplete} ${text}`)) return "payment";
  if (autocomplete.includes("address") || /\b(address|street)\b/.test(text)) return "address";
  if (autocomplete === "address-level2" || /\b(city|town)\b/.test(text)) return "city";
  if (autocomplete === "address-level1" || /\b(state|province|region)\b/.test(text)) return "region";
  if (autocomplete === "postal-code" || /\b(zip|postal)\b/.test(text)) return "postal";
  if (autocomplete === "country" || /\bcountry\b/.test(text)) return "country";
  if (type === "date" || autocomplete.includes("bday") || /\bdate\b/.test(text)) return "date";
  if (/\b(quantity|qty)\b/.test(text) || type === "number") return "quantity";
  if (/\b(promo|coupon|discount)\b/.test(text)) return "promo";
  if (autocomplete.includes("name") || /\b(full )?name\b/.test(text)) return "name";
  return undefined;
}

/** A code-owned page-stage enum; it never forwards the URL or page copy. */
export function safeStageV2(url: string, elements: readonly InteractiveElement[]): SafeStageV2 {
  const internalUrl = url.toLowerCase();
  if (/(?:success|complete|confirm|thank-you|thank_you|finished|done)(?:[/?#-]|$)/.test(internalUrl)) {
    return "complete";
  }
  if (elements.some((el) => intentOf(el) === "payment" || intentOf(el) === "checkout")) return "checkout";
  if (elements.some((el) => intentOf(el) === "add_to_cart")) return "browse";
  if (elements.some((el) => intentOf(el) === "login" || intentOf(el) === "signup")) return "auth";
  if (elements.some((el) => roleOf(el) === "textbox" || roleOf(el) === "select")) return "form";
  if (/(?:cart|basket|bag)(?:[/?#-]|$)/.test(internalUrl)) return "cart";
  return "browse";
}

function frameOf(el: InteractiveElement, pageOrigin: string): SafeControlV2["frame"] {
  if (el.frameOrigin === null || el.frameOrigin === undefined) return "main";
  return el.frameOrigin === pageOrigin ? "same_origin" : "cross_origin";
}

function upstreamSelected(el: InteractiveElement, selected: readonly BrowserUseSelectedNode[]): boolean {
  const tag = el.tag.toLowerCase();
  const role = (el.role ?? "").toLowerCase();
  return selected.some((node) => {
    if (node.tag.toLowerCase() !== tag) return false;
    if (role.length > 0 && node.role !== null && node.role.toLowerCase() !== role) return false;
    // Browser-use owns the selection. Its backend node ids are not available
    // in TS's action inventory, so matching is structural; raw names are never
    // copied, compared, logged, or retained on this side of the seal.
    return true;
  });
}

export function safeV2Ref(secret: Buffer, legacyRef: string): string {
  return `@e:${createHmac("sha256", secret).update(legacyRef).digest("base64url").slice(0, 18)}`;
}

export function buildSafeControlsV2(args: {
  elements: readonly InteractiveElement[];
  legacyRefs: ReadonlyMap<InteractiveElement, string>;
  secret: Buffer;
  pageOrigin: string;
  selected: readonly BrowserUseSelectedNode[];
}): { rows: SafeControlV2[]; byRef: Map<string, string> } {
  const rows: Array<{ row: SafeControlV2; priority: number }> = [];
  const byRef = new Map<string, string>();
  for (const el of args.elements) {
    if (el.visible !== true || el.topmost === false) continue;
    const role = roleOf(el);
    const legacy = args.legacyRefs.get(el);
    if (role === null || legacy === undefined || !upstreamSelected(el, args.selected)) continue;
    const ref = safeV2Ref(args.secret, legacy);
    byRef.set(ref, legacy);
    const state = stateOf(el);
    const action = intentOf(el);
    const field = fieldOf(el);
    const cardChoice = el.cardRadioGroup;
    const row: SafeControlV2 = {
      ref,
      role,
      visibility: el.inViewport ? "viewport" : "near",
      frame: frameOf(el, args.pageOrigin),
      ...(state === undefined ? {} : { state }),
      ...(action === undefined ? {} : { action }),
      ...(field === undefined ? {} : { field }),
      ...(cardChoice === null || cardChoice === undefined
        ? {}
        : { choice: `${cardChoice.position}/${cardChoice.total}` }),
    };
    rows.push({ row, priority: (el.inViewport ? 0 : 10) + (role === "button" ? 0 : 1) });
  }
  rows.sort((a, b) => a.priority - b.priority || a.row.ref.localeCompare(b.row.ref));
  return { rows: rows.map(({ row }) => row), byRef };
}

export function encodeV2Page(args: {
  sessionId: string;
  generation: number;
  stage: SafeStageV2;
  rows: readonly SafeControlV2[];
  cursorFor: (offset: number) => string;
  offset?: number;
  unchanged?: boolean;
}): { payload: Record<string, unknown>; nextOffset: number } {
  const offset = args.offset ?? 0;
  if (args.unchanged === true && offset === 0) {
    return {
      payload: {
        format: "compact-v2",
        session_id: args.sessionId,
        generation: args.generation,
        stage: args.stage,
        delta: true,
      },
      nextOffset: 0,
    };
  }
  const visible: WireControlV2[] = [];
  // Initial observations stay decisively small. Overflow is retrieved through
  // the in-MCP query cursor, never a shell-readable snapshot file.
  const pageEnd = offset === 0 ? Math.min(args.rows.length, FIRST_PAGE_ROW_LIMIT) : args.rows.length;
  for (let index = offset; index < pageEnd; index += 1) {
    const candidate = args.rows[index]!;
    const remainder = args.rows.length - (index + 1);
    const payload: Record<string, unknown> = {
      format: "compact-v2",
      session_id: args.sessionId,
      generation: args.generation,
      stage: args.stage,
      safe_table: [...visible, wireControl(candidate)],
      ...(remainder > 0 ? { overflow: { remaining: remainder, next_cursor: args.cursorFor(index + 1) } } : {}),
    };
    if (Buffer.byteLength(JSON.stringify(payload), "utf8") > OBSERVE_V2_MAX_WIRE_BYTES) break;
    visible.push(wireControl(candidate));
  }
  const nextOffset = offset + visible.length;
  const remaining = args.rows.length - nextOffset;
  const payload: Record<string, unknown> = {
    format: "compact-v2",
    session_id: args.sessionId,
    generation: args.generation,
    stage: args.stage,
    safe_table: visible,
    ...(remaining > 0 ? { overflow: { remaining, next_cursor: args.cursorFor(nextOffset) } } : {}),
  };
  // The fixed fields are deliberately tiny, so failure means a hostilely long
  // session id/cursor. Fail closed rather than exceeding the wire contract.
  if (Buffer.byteLength(JSON.stringify(payload), "utf8") > OBSERVE_V2_MAX_WIRE_BYTES) {
    throw new Error("compact-v2 budget metadata exceeded");
  }
  return { payload, nextOffset };
}
