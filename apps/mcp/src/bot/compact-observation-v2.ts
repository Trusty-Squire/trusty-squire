/**
 * Semantic essentials are sticky across V2 deltas. A repeat observation only
 * needs to carry them when their already-sealed representation changed; the
 * consumer retains the prior title/heading just like it retains safe_table.
 */
export function equalSafePageSemanticsV2(
  left: SafePageSemanticsV2,
  right: SafePageSemanticsV2,
): boolean {
  return left.title === right.title && (left.headings?.[0] ?? "") === (right.headings?.[0] ?? "");
}

/** `@e:` + a truncated session-secret HMAC of (document epoch, fingerprint). */
export const COMPACT_V2_HANDLE_LENGTH = 10;
const COMPACT_V2_HANDLE_RE = new RegExp(`^@e:[A-Za-z0-9_-]{${COMPACT_V2_HANDLE_LENGTH}}$`);
const COMPACT_V2_LABEL_RE = /^@[a-z0-9]+(?:-[a-z0-9]+)*$/;

export function isCompactV2Handle(target: string): boolean {
  return COMPACT_V2_HANDLE_RE.test(target);
}

/** The `@label` alias form, distinguishable from a handle by its `@e:` prefix. */
export function isCompactV2Label(target: string): boolean {
  return COMPACT_V2_LABEL_RE.test(target);
}

/**
 * Resolve a handle only when it is well-formed AND a member of the current
 * snapshot's sealed map. Callers must never turn an unknown @e: value into a
 * label or legacy-ref lookup. The handle is document-scoped by construction
 * (the epoch is hashed into it), so a ref from a replaced document finds no
 * live match rather than resolving onto whatever now occupies its position.
 */
export function compactV2LegacyRefForHandle(
  handles: ReadonlyMap<string, string>,
  target: string,
): string | null {
  if (!isCompactV2Handle(target)) return null;
  return handles.get(target) ?? null;
}

const LABEL_MAX_CHARS = 32;

/**
 * The addressable alias for a screened control description. Slugified so the
 * agent can type it back verbatim; `undefined` when the description screened
 * out or carries no alphanumeric content.
 */
export function controlLabelV2(description: string | undefined): string | undefined {
  if (description === undefined) return undefined;
  const slug = description
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, LABEL_MAX_CHARS)
    .replace(/-+$/g, "");
  return slug.length === 0 ? undefined : `@${slug}`;
}

type WireControlV2 = [string, string, string?];

// The protocol is intentionally positional to keep repeated observes small.
// Tuple schema: [ref, role(b/l/t/s/c/r/tb/m/f), optional compact description].
// The description starts with the `@label` alias (itself a valid act target)
// and appends only present code-owned facts (`s=`, `a=`, `f=`, `q=`, `x=`). It
// is deliberately one sparse string rather than nullable columns:
// checked/unchecked, disabled, action, field, card choice, and frame context
// remain distinguishable without paying for empty slots on every row. The
// label's slug charset excludes `|` and `=`, so no escaping is needed.
function wireControl(row: SafeControlV2): WireControlV2 {
  const role: Record<SafeRoleV2, string> = {
    button: "b",
    link: "l",
    textbox: "t",
    select: "s",
    checkbox: "c",
    radio: "r",
    tab: "tb",
    menuitem: "m",
    file: "f",
  };
  const facts = [
    row.label,
    ...(row.state === undefined ? [] : [`s=${row.state}`]),
    ...(row.action === undefined ? [] : [`a=${row.action}`]),
    ...(row.field === undefined ? [] : [`f=${row.field}`]),
    ...(row.choice === undefined ? [] : [`q=${row.choice}`]),
    ...(row.frame === "main" ? [] : [`x=${row.frame === "same_origin" ? "s" : "x"}`]),
  ].filter((value): value is string => value !== undefined);
  return facts.length === 0
    ? [row.ref, role[row.role]]
    : [row.ref, role[row.role], facts.join("|")];
}

const SAFE_DESCRIPTION_MAX_CHARS = 40;
// PAYMENT-ONLY description screening. Card material is the whole of it: a
// Luhn-valid PAN span and a labeled CVV/CVC value. Everything else a page
// renders — OAuth button copy, an email address in a field label, a Gmail
// subject line, a street address, a shipping option, and yes a rendered API
// key or recovery code — is ordinary content the driving agent needs to read.
//
// This replaces a closed-vocabulary allowlist grammar (~120 permitted words)
// plus email/entropy/OTP/credential-shape rejections. That grammar is what
// blanked auth pages (an unlisted word anywhere in a label screened the whole
// label out) and whole Gmail views, so the agent saw unlabeled role letters
// where a page full of legible controls existed.
const CARD_SECURITY_VALUE_RE = /\b(?:cvv|cvc|security\s*code)\s*[:#-]?\s*\d{3,4}\b/i;
const PAN_MAX_SPAN_CHARS = 96;

function luhnValid(digits: string): boolean {
  let sum = 0;
  let double = false;
  for (let index = digits.length - 1; index >= 0; index -= 1) {
    let digit = Number(digits[index]);
    if (double) {
      digit *= 2;
      if (digit > 9) digit -= 9;
    }
    sum += digit;
    double = !double;
  }
  return sum % 10 === 0;
}

/** A rendered card number: 13-19 digits in one span that passes Luhn. */
function containsLuhnPan(value: string): boolean {
  const positions = Array.from(value.matchAll(/\d/g), (match) => match.index);
  for (let start = 0; start + 13 <= positions.length; start += 1) {
    const maxLength = Math.min(19, positions.length - start);
    for (let length = 13; length <= maxLength; length += 1) {
      const span = positions.slice(start, start + length);
      if (span[span.length - 1]! - span[0]! + 1 > PAN_MAX_SPAN_CHARS) break;
      if (luhnValid(span.map((position) => value[position]).join(""))) return true;
    }
  }
  return false;
}

/** The one screen every page-derived string passes: it must carry no card value. */
function carriesPaymentMaterial(value: string): boolean {
  return containsLuhnPan(value) || CARD_SECURITY_VALUE_RE.test(value);
}

